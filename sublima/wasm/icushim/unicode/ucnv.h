static inline UConverter *ucnv_open(const char *name, UErrorCode *s) {
  static UConverter u16 = {0}, c1252 = {1252}, c1250 = {1250}, c1251 = {1251};
  *s = U_ZERO_ERROR;
  if (!strcmp(name, "UTF-16LE")) return &u16;
  if (!strcmp(name, "windows-1250")) return &c1250;
  if (!strcmp(name, "windows-1251")) return &c1251;
  return &c1252;
}
static inline void ucnv_close(UConverter *) {}
static inline UChar32 ucnv_getNextUChar(UConverter *c, const char **src, const char *limit, UErrorCode *s) {
  const uint8_t *p = (const uint8_t *)*src;
  if (*src >= limit) { *s = U_INDEX_OUTOFBOUNDS_ERROR; return 0xffff; }
  *s = U_ZERO_ERROR;
  if (c->kind == 0) {
    if (limit - *src < 2) { *src = limit; *s = U_INVALID_CHAR_FOUND; return 0xffff; }
    uint32_t u = p[0] | (p[1] << 8); *src += 2;
    if (u >= 0xd800 && u <= 0xdbff && limit - *src >= 2) {
      const uint8_t *q = (const uint8_t *)*src; uint32_t l = q[0] | (q[1] << 8);
      if (l >= 0xdc00 && l <= 0xdfff) { *src += 2; return 0x10000 + ((u - 0xd800) << 10) + (l - 0xdc00); }
    }
    return (UChar32)u;
  }
  uint8_t b = p[0]; *src += 1;
  if (b < 0x80) return b;
  if (c->kind == 1250) return sub_cp1250[b - 0x80];
  if (c->kind == 1251) {
    if (b >= 0xc0) return 0x0410 + (b - 0xc0);
    static const uint16_t t[64] = {0x0402,0x0403,0x201A,0x0453,0x201E,0x2026,0x2020,0x2021,0x20AC,0x2030,0x0409,0x2039,0x040A,0x040C,0x040B,0x040F,
      0x0452,0x2018,0x2019,0x201C,0x201D,0x2022,0x2013,0x2014,0xFFFD,0x2122,0x0459,0x203A,0x045A,0x045C,0x045B,0x045F,
      0x00A0,0x040E,0x045E,0x0408,0x00A4,0x0490,0x00A6,0x00A7,0x0401,0x00A9,0x0404,0x00AB,0x00AC,0x00AD,0x00AE,0x0407,
      0x00B0,0x00B1,0x0406,0x0456,0x0491,0x00B5,0x00B6,0x00B7,0x0451,0x2116,0x0454,0x00BB,0x0458,0x0405,0x0455,0x0457};
    return t[b - 0x80];
  }
  if (b < 0xa0) return sub_cp1252[b - 0x80];
  return b;
}
